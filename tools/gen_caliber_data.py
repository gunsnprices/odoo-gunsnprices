"""Generate gunsnprices_product_specs/data/gnp_caliber_data.xml from the bundled caliber list.

Run after tools/vendor_gunsnprices.py:  python tools/gen_caliber_data.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "gunsnprices_product_specs" / "lib" / "gunsnprices" / "data" / "calibers.json"
OUT = ROOT / "gunsnprices_product_specs" / "data" / "gnp_caliber_data.xml"


def xmlid(code: str) -> str:
    return "caliber_" + re.sub(r"[^a-z0-9_]", "_", code.lower())


def main() -> None:
    calibers = json.loads(SRC.read_text(encoding="utf-8"))["calibers"]
    # sequence: most listed calibers first (ties by name), so pickers show 9mm before 5.7x28mm
    ranked = sorted(calibers, key=lambda c: (-c.get("n", 0), c["name"]))
    seq = {c["id"]: i + 1 for i, c in enumerate(ranked)}
    ids = [xmlid(c["id"]) for c in calibers]
    if len(set(ids)) != len(ids):
        raise SystemExit("xml ids collide")
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by tools/gen_caliber_data.py from the gunsnprices caliber list (CC BY 4.0, GunsNPrices). -->",
           "<odoo>"]
    for c in sorted(calibers, key=lambda c: seq[c["id"]]):
        aliases = [a for a in c.get("aliases", []) if a.strip() and a != c["name"]]
        out.append(f'    <record id="{xmlid(c["id"])}" model="gnp.caliber">')
        out.append(f'        <field name="name">{escape(c["name"])}</field>')
        out.append(f'        <field name="code">{escape(c["id"])}</field>')
        out.append(f'        <field name="caliber_type">{escape(c["type"])}</field>')
        out.append(f'        <field name="sequence">{seq[c["id"]]}</field>')
        if aliases:
            out.append(f'        <field name="aliases">{escape(chr(10).join(aliases))}</field>')
        if c.get("url"):
            out.append(f'        <field name="reference_url">{escape(c["url"])}</field>')
        out.append("    </record>")
    out.append("</odoo>")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(calibers)} calibers -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
